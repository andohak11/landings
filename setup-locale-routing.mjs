#!/usr/bin/env node
/**
 * setup-locale-routing.mjs  (language-only, clean URL)
 *
 * Layout per landing — every locale is a folder:
 *   <landing>/default/index.html + assets/   (required fallback)
 *   <landing>/fr/index.html + assets/
 *   <landing>/ru/index.html + assets/
 *
 * Behaviour:
 *   - The browser bar stays clean at '/'. Middleware (matcher '/') reads
 *     Accept-Language, picks a matching locale folder (else 'default'), and
 *     transparently REWRITES '/' -> /{locale}/index.html.
 *   - A <base href="/{locale}/"> injected into each locale's index.html makes
 *     all relative refs (assets + inline-CSS url()) load from that folder, so
 *     assets are served directly & cached (they bypass middleware).
 *   - Each locale is also reachable directly at /{locale}/ .
 *   - QA override: /?lang=fr   (/?lang=xx forces default).
 *
 * Generates middleware.js per landing. Idempotent & re-runnable — add an fr/ or
 * ru/ folder and re-run to activate that language.
 *
 * Usage:  node setup-locale-routing.mjs [rootDir]
 */

import fs from "node:fs";
import path from "node:path";

const ROOT = process.argv[2] || ".";
const SKIP = new Set([".git", ".vercel", "node_modules", "assets"]);
const BASE_RE = /<base href="\/[^"]*\/"><!--LR-BASE-->/; // matches any previously-injected base

/** locale folders = immediate dirs (not assets/dot) that contain an index.html */
function localesOf(landingDir) {
  return fs
    .readdirSync(landingDir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith(".") && !SKIP.has(e.name))
    .filter((e) => fs.existsSync(path.join(landingDir, e.name, "index.html")))
    .map((e) => e.name)
    .sort();
}

/** Insert/refresh <base href="/{locale}/"> right after <head> in a locale index.html. */
function setBase(indexPath, locale) {
  let html = fs.readFileSync(indexPath, "utf8");
  const block = `<base href="/${locale}/"><!--LR-BASE-->`;
  if (BASE_RE.test(html)) {
    const next = html.replace(BASE_RE, block);
    if (next !== html) fs.writeFileSync(indexPath, next);
    return "refreshed";
  }
  const head = /(<head[^>]*>)/i;
  if (!head.test(html)) { console.warn(`  (!) no <head> in ${indexPath}`); return "skipped"; }
  fs.writeFileSync(indexPath, html.replace(head, `$1${block}`));
  return "injected";
}

function writeMiddleware(landingDir, nonDefaultLocales) {
  const code = `// AUTO-GENERATED by setup-locale-routing.mjs — do not edit by hand.
// Clean-URL language routing. Runs only on the document entry ('/').
// Picks a locale from Accept-Language (else 'default') and rewrites '/' to it.
export const config = { matcher: '/' };

const LOCALES = ${JSON.stringify(nonDefaultLocales)}; // non-default locales that exist

function pickLocale(al) {
  if (!al) return null;
  const ranked = al
    .split(',')
    .map((part) => {
      const [tag, q] = part.trim().split(';q=');
      return { lang: (tag || '').toLowerCase().split('-')[0], q: q ? parseFloat(q) : 1 };
    })
    .sort((a, b) => b.q - a.q);
  for (const { lang } of ranked) if (LOCALES.includes(lang)) return lang;
  return null;
}

export default function middleware(request) {
  const url = new URL(request.url);
  const override = url.searchParams.get('lang');
  let locale =
    override != null
      ? (LOCALES.includes(override) ? override : 'default')
      : (pickLocale(request.headers.get('accept-language')) || 'default');

  url.pathname = '/' + locale + '/index.html';
  return new Response(null, { headers: { 'x-middleware-rewrite': url.toString() } });
}
`;
  fs.writeFileSync(path.join(landingDir, "middleware.js"), code);
}

// a landing = immediate subdir of ROOT that has at least one locale folder
const landings = fs
  .readdirSync(ROOT, { withFileTypes: true })
  .filter((e) => e.isDirectory() && !e.name.startsWith(".") && !SKIP.has(e.name))
  .map((e) => path.join(ROOT, e.name))
  .filter((dir) => localesOf(dir).length > 0);

if (!landings.length) { console.log("No landings with locale folders found."); process.exit(0); }

for (const dir of landings) {
  const locales = localesOf(dir);
  if (!locales.includes("default")) console.warn(`  (!) ${path.basename(dir)} has no default/ folder — fallback will 404`);
  const baseStatus = locales.map((loc) => `${loc}:${setBase(path.join(dir, loc, "index.html"), loc)}`);
  const nonDefault = locales.filter((l) => l !== "default");
  writeMiddleware(dir, nonDefault);
  // drop obsolete device-era artifacts
  for (const f of ["vercel.json", "variants.json"]) {
    const p = path.join(dir, f);
    if (fs.existsSync(p)) fs.rmSync(p);
  }
  console.log(`${path.basename(dir)}: locales [${locales.join(", ")}]  base(${baseStatus.join(" ")})  -> middleware.js`);
}
console.log("\nDone. Redeploy each landing to apply.");
